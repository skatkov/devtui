package generator

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

func generateMarkdownForCommand(cmd *cobra.Command, sitePath string) {
	var buf bytes.Buffer

	// Write front matter
	fmt.Fprintf(&buf, `---
title: %s
parent: CLI
---

`, cmd.Name())

	// Generate the markdown content for main command
	if err := doc.GenMarkdown(cmd, &buf); err != nil {
		log.Fatal(err)
	}

	// Add subcommands to the same file
	for _, subCmd := range cmd.Commands() {
		// Skip help command
		if subCmd.Name() == "help" {
			continue
		}

		// Add a separator and subcommand documentation
		buf.WriteString("\n---\n\n")

		if err := doc.GenMarkdown(subCmd, &buf); err != nil {
			log.Fatal(err)
		}
	}

	err := os.WriteFile(filepath.Join(sitePath, cmd.Name()+".md"), []byte(cleanMarkdown(buf.String())), 0o644)
	if err != nil {
		log.Fatal(err)
	}
}

// cleanMarkdown removes the cobra title, footer and SEE ALSO section and tidies code blocks.
func cleanMarkdown(content string) string {
	lines := strings.Split(content, "\n")
	processedLines := make([]string, 0, len(lines))
	inSeeAlso := false
	inCodeBlock := false
	codeBlockLines := []string{}
	lastSection := ""

	for _, line := range lines {
		if strings.HasPrefix(line, "# ") {
			// Skip the auto-generated title
			continue
		}
		if strings.HasPrefix(line, "###### Auto generated by") {
			// Skip the auto-generated footer
			continue
		}
		if strings.HasPrefix(line, "### SEE ALSO") {
			// Start skipping SEE ALSO section
			inSeeAlso = true
			continue
		}
		if inSeeAlso && !strings.HasPrefix(line, "### ") && !strings.HasPrefix(line, "## ") && line != "---" {
			// Skip lines in SEE ALSO section
			continue
		}
		// Any heading or the subcommand separator ends the SEE ALSO section
		inSeeAlso = false

		// Track current section
		if strings.HasPrefix(line, "### ") {
			lastSection = strings.TrimSpace(line)
		}

		// Handle code blocks
		if strings.TrimSpace(line) == "```" && !inCodeBlock {
			// Start of code block
			inCodeBlock = true
			// Add bash language hint for Examples and Synopsis sections
			if lastSection == "### Examples" || lastSection == "### Synopsis" {
				processedLines = append(processedLines, "```bash")
			} else {
				processedLines = append(processedLines, "```")
			}
			continue
		}
		if strings.TrimSpace(line) == "```" && inCodeBlock {
			// End of code block - process collected lines
			for _, codeLine := range codeBlockLines {
				// Remove leading whitespace for Examples sections only
				if lastSection == "### Examples" {
					trimmed := strings.TrimLeft(codeLine, " \t")
					if trimmed != "" {
						processedLines = append(processedLines, trimmed)
					}
				} else {
					processedLines = append(processedLines, codeLine)
				}
			}
			processedLines = append(processedLines, "```")
			inCodeBlock = false
			codeBlockLines = []string{}
			continue
		}
		if inCodeBlock {
			// Collect lines inside code block
			codeBlockLines = append(codeBlockLines, line)
			continue
		}

		processedLines = append(processedLines, line)
	}

	return strings.Join(processedLines, "\n")
}

// GenerateCLIDocumentation writes a page per root subcommand into sitePath, skipping version.
func GenerateCLIDocumentation(rootCmd *cobra.Command, sitePath string) {
	for _, cmd := range rootCmd.Commands() {
		// Skip version command
		if cmd.Name() == "version" {
			continue
		}

		// Generate documentation for the command (including subcommands)
		generateMarkdownForCommand(cmd, sitePath)
	}
}
